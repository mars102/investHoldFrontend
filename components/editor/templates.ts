/**
 * Ready-made document templates for the editor. Fill-in places are Ophx template fields:
 * <span class="ophx-field" contenteditable="true" data-ophx-field="id" ...>.
 * Field ids must be unique within a template (A-Z a-z 0-9 . _ -).
 *
 * These are simplified samples for demonstration, not legal advice.
 */

export interface DocumentTemplate {
  id: string
  title: string
  description: string
  icon: string
  html: string
}

/** Inline template field. Required by default. */
function f(id: string, label: string, required = true): string {
  const req = required ? ' data-ophx-required="true"' : ''
  return `<span class="ophx-field" contenteditable="true" data-ophx-field="${id}" data-ophx-label="${label}"${req}></span>`
}

/** Field ids must be ASCII: stable id prefix for each party name. */
const PARTY_IDS: Record<string, string> = {
  Поставщик: 'supplier',
  Покупатель: 'buyer',
  Исполнитель: 'contractor',
  Заказчик: 'customer',
  Арендодатель: 'landlord',
  Арендатор: 'tenant',
  Займодавец: 'lender',
  Заёмщик: 'borrower',
  'Раскрывающая сторона': 'discloser',
  'Получающая сторона': 'recipient',
}

function partyDetails(party: string): string {
  const id = PARTY_IDS[party]
  return `<p>${f(`${id}_name`, `${party}: наименование / ФИО`)}</p>
    <p>ИНН: ${f(`${id}_inn`, `${party}: ИНН`)}</p>
    <p>Адрес: ${f(`${id}_addr`, `${party}: адрес`)}</p>
    <p>Подпись: ________</p>`
}

/** Shared details and signature block for two parties. */
function sig(left: string, right: string): string {
  return `
<h2>Реквизиты и подписи сторон</h2>
<table>
  <tr><th>${left}</th><th>${right}</th></tr>
  <tr><td>${partyDetails(left)}</td><td>${partyDetails(right)}</td></tr>
</table>`
}

function header(title: string): string {
  return `<h1>${title} № ${f('number', 'Номер договора')}</h1>
<p>г. ${f('city', 'Город')}, ${f('date', 'Дата заключения')}</p>`
}

